// Language Engine State
function getInitialLanguage() {
  const savedLang = localStorage.getItem('lang');
  if (savedLang && (savedLang === 'th' || savedLang === 'en')) {
    return savedLang;
  }
  return 'th'; // Default to Thai
}

function applyLanguage(lang) {
  const currentLang = (lang === 'en') ? 'en' : 'th';
  document.documentElement.setAttribute('lang', currentLang);
  localStorage.setItem('lang', currentLang);

  // Update Language Toggle Button UI
  const langText = document.getElementById('lang-text');
  if (langText) {
    langText.textContent = (currentLang === 'th') ? 'TH / EN' : 'EN / TH';
  }

  // Translate all elements with data-i18n attribute
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang] && translations[currentLang][key]) {
      el.innerHTML = translations[currentLang][key];
    }
  });
}

let currentLang = getInitialLanguage();

document.addEventListener('DOMContentLoaded', () => {
  applyLanguage(currentLang);

  // Attach Language Switcher Button Click Event
  const langToggleBtn = document.getElementById('lang-toggle');
  if (langToggleBtn) {
    langToggleBtn.addEventListener('click', () => {
      currentLang = (currentLang === 'th') ? 'en' : 'th';
      applyLanguage(currentLang);
    });
  }

  // Create & Inject Topbar Scroll Progress Indicator (Wix Showcase Style)
  const topbar = document.querySelector('.topbar');
  if (topbar && !document.getElementById('scroll-progress')) {
    const progressBar = document.createElement('div');
    progressBar.id = 'scroll-progress';
    progressBar.className = 'scroll-progress-bar';
    topbar.appendChild(progressBar);
  }

  window.addEventListener('scroll', () => {
    const winScroll = document.documentElement.scrollTop || document.body.scrollTop;
    const height = document.documentElement.scrollHeight - document.documentElement.clientHeight;
    const scrolled = height > 0 ? (winScroll / height) * 100 : 0;
    const progressBar = document.getElementById('scroll-progress');
    if (progressBar) {
      progressBar.style.width = scrolled + '%';
    }
  }, { passive: true });

  // Universal Intersection Observer for Scroll Reveals
  const revealObserver = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        entry.target.classList.add('in-view');
      }
    });
  }, { threshold: 0.1, rootMargin: '0px 0px -50px 0px' });

  document.querySelectorAll('.reveal').forEach(el => revealObserver.observe(el));
});
